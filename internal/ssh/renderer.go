package ssh

import (
	"bytes"
	"fmt"
	"time"
)

type Host struct {
	Alias               string
	HostName            string
	User                string
	Port                int
	IdentityFile        string
	ProxyJump           string
	ForwardAgent        bool
	Compression         bool
	ServerAliveInterval int
	ServerAliveCountMax int
	ConnectTimeout      int
}

func RenderConfig(hosts []Host) string {
	var buf bytes.Buffer
	buf.WriteString("# ----------------------------------------------------------------------\n")
	buf.WriteString("# Generated by aTerm\n")
	buf.WriteString("# Do not edit this file manually.\n")
	buf.WriteString(fmt.Sprintf("# Updated: %s\n", time.Now().UTC().Format(time.RFC3339)))
	buf.WriteString("# ----------------------------------------------------------------------\n\n")

	for _, host := range hosts {
		buf.WriteString(fmt.Sprintf("Host %s\n", host.Alias))
		writeOption(&buf, "HostName", host.HostName)
		writeOption(&buf, "User", host.User)
		if host.Port > 0 {
			writeOption(&buf, "Port", fmt.Sprintf("%d", host.Port))
		}
		writeOption(&buf, "IdentityFile", host.IdentityFile)
		writeOption(&buf, "ProxyJump", host.ProxyJump)
		if host.ForwardAgent {
			writeOption(&buf, "ForwardAgent", "yes")
		}
		if host.Compression {
			writeOption(&buf, "Compression", "yes")
		}
		if host.ServerAliveInterval > 0 {
			writeOption(&buf, "ServerAliveInterval", fmt.Sprintf("%d", host.ServerAliveInterval))
		}
		if host.ServerAliveCountMax > 0 {
			writeOption(&buf, "ServerAliveCountMax", fmt.Sprintf("%d", host.ServerAliveCountMax))
		}
		if host.ConnectTimeout > 0 {
			writeOption(&buf, "ConnectTimeout", fmt.Sprintf("%d", host.ConnectTimeout))
		}
		buf.WriteByte('\n')
	}

	return buf.String()
}

func writeOption(buf *bytes.Buffer, key string, value string) {
	if value == "" {
		return
	}
	buf.WriteString(fmt.Sprintf("    %s %s\n", key, value))
}
